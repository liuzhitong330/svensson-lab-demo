const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname,"..");
const api = require(path.join(root,"app.js"));
const brp = JSON.parse(fs.readFileSync(path.join(root,"brp-data.json"),"utf8"));
const cancer = JSON.parse(fs.readFileSync(path.join(root,"cancer-data.json"),"utf8"));
let settings = 0;
for(const c of brp.conditions.slice(2)) for(const ceiling of [10,20,25,35,50]) for(const time of [.5,1,1.5,2,3]) {
  const r = api.peptideResult(c,ceiling,time);
  assert.equal(r.residuals.length,3);
  assert.ok(r.residuals.every(Number.isFinite));
  assert.equal(r.eligible,r.complete && r.residuals.every(v=>Math.abs(v)<=ceiling));
  if(c.id==="R3A") assert.equal(r.eligible,false);
  settings++;
}
assert.equal(settings,300);
const l8a=brp.conditions.find(c=>c.id==="L8A");
assert.equal(api.peptideIdentity(brp,l8a).precursorPosition,393);
assert.equal(api.peptideIdentity(brp,brp.conditions.find(c=>c.id==="L5A")).precursorPosition,390);
assert.equal(api.peptideIdentity(brp,brp.conditions.find(c=>c.id==="C12A")).precursorPosition,397);
assert.equal(api.peptideIdentity(brp,null).precursorPosition,null);
assert.equal(api.peptideResult(l8a,25,.5).eligible,true);
assert.equal(api.peptideResult(l8a,20,.5).eligible,false);
assert.equal(api.peptideResult(l8a,25,1.5).eligible,false);
assert.equal(api.peptideResult(l8a,25,3).eligible,false);
assert.equal(api.peptideResult(l8a,25,0).available,false);
assert.equal(api.peptideResult(null,25,.5).eligible,false);
assert.equal(api.peptideResult(l8a,NaN,.5).eligible,false);
const reversed=structuredClone(l8a); reversed.ns1.retained_activity=-.99;
assert.equal(api.peptideResult(reversed,25,.5).eligible,false);
const pcsv=api.peptideCSV(brp,25,.5);
assert.equal(pcsv.trim().split("\r\n").length,13);
assert.ok(pcsv.includes('"L8A"'));
assert.ok(pcsv.includes('"repeat missing measurement"'));
assert.ok(!pcsv.includes("undefined"));
assert.equal(api.mean([1,2,3]),2);
assert.equal(api.mean([]),null);
assert.equal(api.fmt(null),"not available");
const positiveAxis = api.niceAxis([0, 185.5, 1325.2], true);
assert.equal(positiveAxis.low,0);
assert.deepEqual(positiveAxis.ticks,[0,500,1000,1500]);
assert.ok(positiveAxis.high >= 1325.2);
const negativeAxis = api.niceAxis([-14.25, 0, 13.72]);
assert.deepEqual(negativeAxis.ticks,[-20,-10,0,10,20]);
assert.ok(negativeAxis.low <= -14.25 && negativeAxis.high >= 13.72);
assert.ok(api.niceAxis([0,0],true).high > 0);
assert.ok(api.niceAxis([]).high > api.niceAxis([]).low);
for(const endpoint of Object.keys(cancer.endpoints)) {
  const values = cancer.endpoints[endpoint].groups.flatMap(group=>group.values);
  const axis = api.niceAxis(values,endpoint!=="mass_change_week22");
  assert.ok(values.every(value=>value>=axis.low && value<=axis.high));
  assert.equal(axis.ticks[0],axis.low);
  assert.equal(axis.ticks.at(-1),axis.high);
  if(endpoint!=="mass_change_week22") assert.equal(axis.low,0);
}
let contexts=0;
const narratives=new Set();
for(const endpoint of Object.keys(cancer.endpoints)) for(const icb of [false,true]) for(const contrast of ["sema","nc"]) {
  const r=api.cancerResult(cancer,endpoint,icb,contrast);
  assert.equal(r.groups.length,3);
  assert.ok(r.groups.every(g=>g.values.length===g.n));
  assert.equal(r.difference,r.target.mean-r.reference.mean);
  assert.equal(r.differenceUnit,endpoint==="tumor_day16"?"mm³":"percentage points");
  if(endpoint==="mass_change_week22") assert.equal(r.icb,false);
  else assert.equal(r.icb,icb);
  const output=api.cancerCSV(cancer,endpoint,icb,contrast);
  assert.equal(output.trim().split("\r\n").length,r.groups.reduce((n,g)=>n+g.n,0)+1);
  assert.ok(!output.includes("undefined"));
  const proposal=api.nextControl(r);
  assert.ok(proposal.title.length>10 && proposal.text.length>50);
  narratives.add(proposal.text);
  contexts++;
}
assert.equal(contexts,12);
assert.equal(narratives.size,10);
assert.equal(api.cancerResult(cancer,"missing",false,"sema"),null);
assert.match(api.cancerCSV(cancer,"missing",false,"sema"),/unavailable/);
assert.ok(api.nextControl(null).text.includes("No comparison"));
console.log(`PASS: ${settings} peptide settings, ${contexts} cancer contexts, CSV, normalization guards and null cases.`);
